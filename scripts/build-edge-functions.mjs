#!/usr/bin/env node
/**
 * Bundle the Supabase Edge Functions with esbuild.
 *
 *   pnpm functions:build
 *
 * Each function's source is `supabase/functions/<name>/src/main.ts`; the bundle is written to
 * `supabase/functions/<name>/bundle.js` and committed. The deployed entrypoint, `index.ts`, is a
 * one-line import of that bundle from the repository on GitHub (branch `main`), so a deploy needs
 * no file upload: push, then deploy (Supabase MCP `deploy_edge_function` with `index.ts`, or
 * `supabase functions deploy <name> --no-verify-jwt`). Workspace packages are inlined; npm
 * packages stay external as `npm:<name>@<version>` specifiers, which the Deno runtime resolves
 * itself (pinned to the versions in the repository's lockfile). CI fails when the committed bundle
 * is out of date.
 */
import { readFile, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const FUNCTIONS = ['catalog-import']

/** npm packages the bundle must not inline: Deno fetches them by `npm:` specifier. */
const NPM = { postgres: '3.4.9', 'drizzle-orm': '0.45.4', zod: '4.6.5' }
const NPM_FILTER = new RegExp(`^(${Object.keys(NPM).join('|')})(/.*)?$`)

/** Never part of a Deno bundle: the embedded database and its driver. */
const NEVER = ['@electric-sql/pglite', '@electric-sql/pglite/*', 'drizzle-orm/pglite']

let esbuild
try {
  esbuild = await import('esbuild')
} catch {
  console.error('esbuild is not installed: run `pnpm install` first')
  process.exit(1)
}

const npmSpecifiers = {
  name: 'npm-specifiers',
  setup(build) {
    build.onResolve({ filter: NPM_FILTER }, (args) => {
      const match = NPM_FILTER.exec(args.path)
      const name = match[1]
      const subpath = match[2] ?? ''
      return { path: `npm:${name}@${NPM[name]}${subpath}`, external: true }
    })
  },
}

for (const name of FUNCTIONS) {
  const entry = path.join(root, 'supabase/functions', name, 'src/main.ts')
  const outfile = path.join(root, 'supabase/functions', name, 'bundle.js')
  await esbuild.build({
    entryPoints: [entry],
    outfile,
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    mainFields: ['module', 'main'],
    conditions: ['import', 'module', 'default'],
    external: [...NEVER, 'node:*'],
    plugins: [npmSpecifiers],
    legalComments: 'none',
    minifySyntax: true,
    minifyWhitespace: false,
    minifyIdentifiers: false,
    banner: {
      js: `// Generated by scripts/build-edge-functions.mjs from supabase/functions/${name}/src/main.ts. Do not edit.`,
    },
    logLevel: 'warning',
  })
  const source = await readFile(outfile, 'utf8')
  const forbidden = ['@electric-sql/pglite', 'drizzle-orm/pglite'].filter((s) => source.includes(`"${s}`) || source.includes(`'${s}`))
  if (forbidden.length) {
    console.error(`${name}: the bundle still references ${forbidden.join(', ')}`)
    process.exit(1)
  }
  // Same bytes on every machine: no trailing differences from the esbuild version banner etc.
  await writeFile(outfile, source.endsWith('\n') ? source : `${source}\n`)
  const size = (await stat(outfile)).size
  console.log(`${name}: ${path.relative(root, outfile)} (${(size / 1024).toFixed(0)} KB)`)
}
